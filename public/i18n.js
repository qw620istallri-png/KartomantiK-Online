const KO_LANGUAGE_KEY = "ko_language";
const KO_LANGUAGES = ["fr", "en", "it"];
const browserLanguage = String(navigator.language || "en").slice(0, 2).toLowerCase();
let currentLanguage = localStorage.getItem(KO_LANGUAGE_KEY) || (KO_LANGUAGES.includes(browserLanguage) ? browserLanguage : "en");
if (!KO_LANGUAGES.includes(currentLanguage)) currentLanguage = "en";

function t(key) {
  return (ui[currentLanguage] && ui[currentLanguage][key]) ?? ui.en[key] ?? key;
}
