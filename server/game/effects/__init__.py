from ..replacements import replacement_checkpoint

class EffectsMixin:
    @replacement_checkpoint("effect")
    def apply_rules_action_result(self, action):
        if self.ended:
            return None
        result = (action.get("ability") or {}).get("result") or {}
        player_id = action.get("controllerId")
        player = self.players.get(player_id)
        if player is None:
            return None
        kind = result.get("kind")
        handler = RULES_RESULT_HANDLERS.get(kind) if isinstance(kind, str) else None
        if handler is None:
            return None
        return getattr(self, handler)(action, result, player_id, player)
